/* Two bounded design/estimation families. The shared host owns time and state. */
(function (root, factory) {
  const node = typeof module === 'object' && module.exports;
  const api = factory(node ? require('./plot-view.js') : root.AtlasPlotView);
  if (node) module.exports = api;
  root.AtlasEstimationExtensions = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function (Plot) {
  'use strict';
  const freeze = value => {
    if (value && typeof value === 'object' && !Object.isFrozen(value)) {
      Object.values(value).forEach(freeze);
      Object.freeze(value);
    }
    return value;
  };
  // Nearest represented approximation to the standard normal 0.975 quantile.
  // The independent Python oracle obtains its quantile from statistics.NormalDist.
  const Z975 = 1.959963984540054;
  const field = (key, label, value, min, max, step, unit, discrete = false) => ({
    key,
    label,
    value,
    min,
    max,
    step,
    unit,
    ...(discrete ? { discrete: true } : {})
  });
  const definitions = freeze({
    'randomized-block-design': {
      title: 'Randomized blocks and within-pair comparisons',
      expression: 'd̄ = (d₁ + d₂ + d₃)/3',
      axis: 'change',
      unit: 'min',
      primaryLabel: 'Mean within-block difference',
      setting:
        'A packing workshop plans one A/B comparison on each of three days. Within each day, randomly assign its two similar parcels to the two methods before measuring. The displayed measurements are constructed; the two selectable assignments illustrate fixed possible allocations, not a random draw.',
      limits:
        'Every day contains both methods once. Constructed A times are 10−b, 10 and 10+b minutes; B times add d−1, d and d+1 minutes respectively. The balanced mean of B−A is descriptive. Blocking removes a common additive day offset from each pair; it does not remove treatment-by-day variation, prove causation or perform ANOVA. Randomization is part of the stated study plan, not generated by this animation.',
      controls: [
        field('change', 'Common B−A shift d', -2, -4, 4, 0.05, 'min'),
        field('blockSpread', 'Day offset size b', 3, 0, 4, 0.05, 'min'),
        {
          key: 'assignment',
          label: 'Displayed within-day assignment',
          value: 'alternating',
          type: 'select',
          options: [
            { value: 'alternating', label: 'A first, B first, A first' },
            { value: 'reversed', label: 'B first, A first, B first' }
          ],
          discrete: true
        }
      ]
    },
    'normal-mean-interval': {
      title: 'A normal-mean interval with known spread',
      expression: 'h = z₀.₉₇₅ σ/√n; I = [x̄ − h, x̄ + h]',
      axis: 'sampleSize',
      unit: 'mm',
      primaryLabel: 'Margin of error h',
      setting:
        'A calibration workshop summarizes independent, identically normally distributed cutting errors by an observed mean x̄. The population standard deviation σ is assumed known from the declared model. Change the whole-number sample size n and inspect the fixed 95% interval procedure for the unknown mean μ.',
      limits:
        'Normal, independent readings with one common mean and known positive population standard deviation are assumed, not tested. No observations are sampled here: changing n holds the entered summary mean fixed to isolate interval width. The repeated-sampling procedure covers fixed μ with probability 0.95 in the ideal model; one computed interval has fixed endpoints and is not assigned a 95% posterior probability. This is an interval for the mean, not a prediction interval for the next reading. If σ is estimated, another procedure is needed. z₀.₉₇₅ is evaluated numerically; 1.96 is only a rounded display.',
      controls: [
        field('sampleSize', 'Independent readings n', 16, 1, 64, 1, 'readings', true),
        field('mean', 'Observed mean error x̄', 0.5, -4, 4, 0.05, 'mm'),
        field('sigma', 'Known population spread σ', 1, 0.25, 2, 0.05, 'mm')
      ]
    }
  });
  const ids = Object.freeze(Object.keys(definitions));
  const has = slug => typeof slug === 'string' && Object.hasOwn(definitions, slug);
  const get = slug => {
    if (!has(slug)) throw new RangeError('Unknown estimation model.');
    return definitions[slug];
  };
  const defaults = slug => Object.fromEntries(get(slug).controls.map(c => [c.key, c.value]));
  const controls = slug => get(slug).controls.map(({ value, ...c }) => ({ ...c }));
  function validateParams(slug, input = {}) {
    const parameters = {},
      errors = [];
    if (!has(slug) || !input || typeof input !== 'object' || Array.isArray(input))
      return {
        valid: false,
        parameters,
        errors: [{ field: 'parameters', message: 'Use the declared input object.' }],
        warnings: []
      };
    const fields = get(slug).controls;
    for (const key of Object.keys(input))
      if (!fields.some(c => c.key === key)) errors.push({ field: key, message: 'Unknown input.' });
    for (const c of fields) {
      const value = Object.hasOwn(input, c.key) ? input[c.key] : c.value;
      if (
        c.type === 'select'
          ? typeof value !== 'string' || !c.options.some(option => option.value === value)
          : typeof value !== 'number' ||
            !Number.isFinite(value) ||
            value < c.min ||
            value > c.max ||
            (c.discrete && !Number.isInteger(value))
      )
        errors.push({
          field: c.key,
          message:
            c.type === 'select'
              ? 'Choose a declared allocation.'
              : 'Use ' +
                (c.discrete ? 'a whole number' : 'a finite number') +
                ' within the displayed bounds.'
        });
      else parameters[c.key] = value;
    }
    return { valid: !errors.length, parameters, errors, warnings: [] };
  }
  function evaluate(slug, input) {
    const checked = validateParams(slug, input);
    if (!checked.valid) return { ...checked, status: 'invalid_parameters', output: null };
    const p = checked.parameters;
    if (slug === 'normal-mean-interval') {
      const standardError = p.sigma / Math.sqrt(p.sampleSize),
        margin = Z975 * standardError;
      return {
        ...checked,
        status: 'valid',
        output: margin,
        standardError,
        criticalValue: Z975,
        lower: p.mean - margin,
        upper: p.mean + margin,
        interval: [p.mean - margin, p.mean + margin],
        width: 2 * margin,
        confidence: 0.95
      };
    }
    const offsets = [-p.blockSpread, 0, p.blockSpread];
    const rows = offsets.map((offset, i) => {
      const a = 10 + offset,
        intended = [p.change - 1, p.change, p.change + 1][i],
        b = a + intended;
      return {
        block: i + 1,
        a,
        b,
        difference: b - a,
        offset,
        first: (i % 2 === 0) === (p.assignment === 'alternating') ? 'A' : 'B',
        intended
      };
    });
    const sumDifferences = rows.reduce((sum, row) => sum + row.difference, 0),
      output = sumDifferences / 3;
    if (
      rows.some(row => row.intended !== 0 && row.difference === 0) ||
      (p.change !== 0 && output === 0)
    )
      return {
        ...checked,
        valid: false,
        status: 'numeric_precision',
        output: null,
        errors: [
          {
            field: 'change',
            message:
              'This change is too small to retain in the constructed readings. Choose a larger change.'
          }
        ]
      };
    return {
      ...checked,
      status: 'valid',
      output: output === 0 ? 0 : output,
      sumDifferences,
      rows,
      blockIndex: rows.map(row => row.block),
      aReadings: rows.map(row => row.a),
      bReadings: rows.map(row => row.b),
      differences: rows.map(row => row.difference),
      firstDifference: rows[0].difference,
      secondDifference: rows[1].difference,
      thirdDifference: rows[2].difference,
      meanA: rows.reduce((sum, row) => sum + row.a, 0) / 3,
      meanB: rows.reduce((sum, row) => sum + row.b, 0) / 3,
      blockCount: 3
    };
  }
  const canInterpolate = (slug, a, b) =>
    validateParams(slug, a).valid &&
    validateParams(slug, b).valid &&
    (slug === 'normal-mean-interval'
      ? a.sampleSize === b.sampleSize
      : a.assignment === b.assignment);
  function specs(slug) {
    const d = get(slug);
    return {
      title: d.title,
      expression: d.expression,
      axis: d.axis,
      unit: d.unit,
      setting: d.setting,
      limits: d.limits,
      primaryLabel: d.primaryLabel,
      views: ['geometry', 'graph'],
      rendererId: slug + '-visual-model',
      sweeps: controls(slug).filter(c => c.type !== 'select'),
      canInterpolate: (a, b) => canInterpolate(slug, a, b),
      readout: (p, r) => ({
        expression: d.expression,
        stats: !r.valid
          ? []
          : slug === 'normal-mean-interval'
            ? [
                {
                  label: 'MARGIN OF ERROR',
                  value: r.output,
                  note: 'mm on either side of the observed mean'
                },
                { label: 'LOWER ENDPOINT', value: r.lower, note: 'mm' },
                { label: 'UPPER ENDPOINT', value: r.upper, note: 'mm' }
              ]
            : [
                {
                  label: 'MEAN B − A',
                  value: r.output,
                  note: 'minutes, using the three within-day differences'
                },
                {
                  label: 'DAY OFFSET SIZE',
                  value: p.blockSpread,
                  note: 'minutes; shared within each day'
                }
              ],
        insight: r.valid
          ? slug === 'normal-mean-interval'
            ? 'More independent readings narrow the interval as 1/√n. Move the observed mean to shift both endpoints without changing the width.'
            : 'Move the common day offset: both methods shift together within each pair. Their difference remains the treatment comparison for that day.'
          : r.errors.map(e => e.message).join(' ')
      })
    };
  }
  const curveValue = (slug, p, value) => {
    const r = evaluate(slug, { ...p, [get(slug).axis]: value });
    return r.valid ? r.output : null;
  };
  const C = {
    bg: '#111e2b',
    ink: '#eef8f4',
    muted: '#a0b5bc',
    grid: '#294352',
    cyan: '#77d8e8',
    gold: '#f5cf78',
    mint: '#c6f276',
    violet: '#b8a1ff'
  };
  const esc = v =>
    String(v ?? '').replace(
      /[&<>"']/g,
      c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]
    );
  const n = v => Number(v.toFixed(5)),
    f = v =>
      Number.isFinite(v) ? String(Number(v.toPrecision(4))).replace(/-/g, '−') : 'unavailable';
  const text = (x, y, value, color = C.ink, size = 18, anchor = 'middle') =>
    `<text x="${n(x)}" y="${n(y)}" fill="${color}" font-size="${size}" text-anchor="${anchor}">${esc(value)}</text>`;
  const line = (x, y, a, b, color = C.grid, extra = '') =>
    `<line x1="${n(x)}" y1="${n(y)}" x2="${n(a)}" y2="${n(b)}" stroke="${color}" ${/(?:^|\s)stroke-width\s*=/.test(extra) ? '' : 'stroke-width="2" '}${extra}/>`;
  const dot = (x, y, color, radius = 6) =>
    `<circle cx="${n(x)}" cy="${n(y)}" r="${radius}" fill="${color}"/>`;
  const mark = (keys, body, role = 'intermediate') =>
    `<g data-quantity="${esc(keys)}" data-story-part="${role}">${body}</g>`;
  const scope = value =>
    Array.from(String(value))
      .map(c => (/^[A-Za-z0-9-]$/.test(c) ? c : '_' + c.codePointAt(0).toString(16) + '_'))
      .join('');
  function frame(slug, body, o, caption) {
    const id = 'estimation-' + scope(o.id || slug),
      width = o.compact ? 360 : 760;
    return `<figure class="visualization-frame"><svg class="visual-scene" viewBox="0 0 ${width} 420" role="img" aria-labelledby="${id}-title ${id}-desc" xmlns="http://www.w3.org/2000/svg"><title id="${id}-title">${esc(get(slug).title)}</title><desc id="${id}-desc">${esc(caption)}</desc><rect width="${width}" height="420" rx="18" fill="${C.bg}"/><g font-family="Inter, system-ui, sans-serif">${body}</g></svg><figcaption class="visual-caption">${esc(caption)}</figcaption></figure>`;
  }
  function geometry(slug, p, r, o) {
    const w = o.compact ? 360 : 760,
      middle = w / 2,
      pin = o.baseline && evaluate(slug, o.baseline);
    let body;
    if (slug === 'randomized-block-design') {
      const left = o.compact ? 58 : 125,
        right = w - (o.compact ? 28 : 70),
        px = v => left + (v / 20) * (right - left);
      body =
        text(middle, 32, 'Compare within each day', C.ink, o.compact ? 21 : 24) +
        mark(
          'aReadings bReadings',
          text(middle, 61, 'Cyan A · gold B · time in minutes', C.muted, o.compact ? 15 : 18),
          'reference'
        );
      for (const v of [0, 10, 20])
        body += line(px(v), 85, px(v), 323) + text(px(v), 345, v, C.muted, 16);
      r.rows.forEach((row, i) => {
        const y = 115 + i * 83;
        body += mark(
          'blockSpread blockIndex aReadings bReadings assignment',
          text(o.compact ? 29 : 65, y + 5, 'Day ' + row.block, C.muted, o.compact ? 14 : 17) +
            text(o.compact ? 29 : 65, y + 27, 'First ' + row.first, C.muted, o.compact ? 14 : 15),
          'reference'
        );
        const differenceKey = ['firstDifference', 'secondDifference', 'thirdDifference'][i];
        body += mark(
          differenceKey + ' differences change blockSpread',
          line(px(row.a), y - 10, px(row.b), y + 10, C.gold, 'stroke-width="3"')
        );
        body += mark('aReadings blockSpread', dot(px(row.a), y - 10, C.cyan), 'reference');
        body += mark('change blockSpread bReadings', dot(px(row.b), y + 10, C.gold), 'input');
        body += mark(
          differenceKey + ' differences',
          text(middle, y + 41, 'B − A = ' + f(row.difference) + ' min', C.gold, o.compact ? 15 : 18)
        );
      });
      body += mark(
        'output sumDifferences blockCount',
        text(middle, 389, 'Mean B − A = ' + f(r.output) + ' min', C.mint, o.compact ? 20 : 25),
        'output'
      );
      if (pin?.valid)
        body += mark(
          'output',
          text(middle, 367, 'Pinned mean: ' + f(pin.output) + ' min', C.violet, 14),
          'reference'
        );
      return frame(
        slug,
        body,
        o,
        'Horizontal position is packing time on one fixed 0–20 minute scale. Each segment keeps its same-day pair. ' +
          (p.assignment === 'alternating'
            ? 'Shown first positions use A, B, A.'
            : 'Shown first positions use B, A, B.') +
          ' These are constructed data and fixed possible allocations; no random sample or significance test runs.'
      );
    }
    const left = o.compact ? 28 : 75,
      right = w - left,
      px = v => left + ((v + 8) / 16) * (right - left);
    body = text(middle, 33, 'Estimate the unknown mean', C.ink, o.compact ? 21 : 25);
    body += mark(
      'sampleSize',
      text(middle, 66, 'Independent readings n = ' + p.sampleSize, C.cyan, o.compact ? 17 : 20),
      'input'
    );
    for (const value of [-8, -4, 0, 4, 8])
      body +=
        line(px(value), 145, px(value), 245, C.grid) +
        text(px(value), 274, f(value), C.muted, o.compact ? 15 : 18);
    body +=
      line(left, 210, right, 210) +
      text(middle, 303, 'Mean error · millimetres', C.muted, o.compact ? 17 : 20);
    body += mark(
      'lower upper output margin interval unknownMean criticalValue sigma sampleSize',
      line(px(r.lower), 210, px(r.upper), 210, C.gold, 'stroke-width="8"') +
        line(px(r.lower), 191, px(r.lower), 229, C.gold) +
        line(px(r.upper), 191, px(r.upper), 229, C.gold),
      'output'
    );
    body += mark(
      'mean',
      dot(px(p.mean), 210, C.cyan, 8) +
        text(px(p.mean), 130, 'x̄ = ' + f(p.mean), C.cyan, o.compact ? 17 : 20),
      'input'
    );
    body += mark(
      'standardError sigma sampleSize',
      line(px(p.mean), 167, px(p.mean + r.standardError), 167, C.mint, 'stroke-width="4"'),
      'intermediate'
    );
    body += mark(
      'output margin lower upper',
      text(middle, 350, 'Margin h ≈ ' + f(r.output) + ' mm', C.gold, o.compact ? 20 : 25),
      'output'
    );
    body += mark(
      'standardError',
      text(
        middle,
        382,
        'Standard error ≈ ' + f(r.standardError) + ' mm',
        C.mint,
        o.compact ? 16 : 19
      )
    );
    if (pin?.valid)
      body += mark(
        'output',
        line(
          px(pin.lower),
          238,
          px(pin.upper),
          238,
          C.violet,
          'stroke-dasharray="6 4" stroke-width="3"'
        ),
        'reference'
      );
    return frame(
      slug,
      body,
      o,
      'Gold shows the computed 95% interval for a fixed unknown population mean, on a fixed −8 to 8 mm axis. Cyan marks the observed mean and mint marks one standard error. Increasing n holds that entered mean fixed; it does not fabricate new readings. The unknown μ has no invented location on the axis.'
    );
  }
  function graph(slug, p, r, o) {
    const d = get(slug),
      c = d.controls[0],
      discrete = !!c.discrete;
    const values = discrete
      ? Array.from({ length: c.max - c.min + 1 }, (_, i) => c.min + i)
      : Array.from({ length: 81 }, (_, i) => c.min + ((c.max - c.min) * i) / 80);
    const current = [
      {
        x: p[c.key],
        y: r.output,
        label: d.primaryLabel,
        quantity: c.key + ' output',
        color: C.mint,
        draggable: !discrete && o.sceneControl !== false
      }
    ];
    const pin = o.baseline && evaluate(slug, o.baseline);
    if (pin?.valid)
      current.push({
        x: pin.parameters[c.key],
        y: pin.output,
        label: 'Pinned result',
        quantity: 'output',
        color: C.violet
      });
    return Plot.render(
      {
        title: d.title,
        description: d.setting,
        x: { ...c, label: c.label },
        y: {
          min: discrete ? 0 : -4.5,
          max: discrete ? 4 : 4.5,
          label: d.primaryLabel + ' (' + d.unit + ')'
        },
        series: [
          {
            id: 'result',
            label: d.primaryLabel,
            quantity: c.key + ' output',
            color: C.gold,
            dots: discrete,
            points: values.map(x => ({ x, y: curveValue(slug, p, x) }))
          }
        ],
        current,
        notes: [
          discrete
            ? 'Dots are whole sample sizes. The normal model with known σ supplies 95% coverage; the graph shows interval margin, not a sampled result.'
            : 'A balanced same-day contrast removes the common additive day offset. This constructed comparison is descriptive, not a significance test.'
        ]
      },
      { ...o, ...(discrete ? { sceneControl: false } : {}) }
    );
  }
  function render(slug, input, o = {}) {
    if (!has(slug)) return '';
    const r = evaluate(slug, input);
    if (!r.valid)
      return frame(
        slug,
        text(o.compact ? 180 : 380, 185, 'Choose supported inputs', C.gold, o.compact ? 21 : 25),
        o,
        r.errors.map(e => e.message).join(' ')
      );
    return o.view === 'graph'
      ? graph(slug, r.parameters, r, o)
      : geometry(slug, r.parameters, r, o);
  }
  return Object.freeze({
    ids,
    has,
    defaults,
    controls,
    specs,
    validateParams,
    evaluate,
    curveValue,
    render,
    canInterpolate,
    criticalValue: Z975
  });
});
