import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createWriter, writeGenerated } = require('../tools/generated_io.cjs');
function fixture(t) {
  const base = path.resolve(os.tmpdir());
  const root = fs.mkdtempSync(path.join(base, 'mathcards-generated-'));
  const safe = () => {
    const resolved = path.resolve(root);
    assert.equal(path.dirname(resolved), base);
    assert.ok(path.basename(resolved).startsWith('mathcards-generated-'));
    return resolved;
  };
  safe();
  t.after(() => fs.rmSync(safe(), { recursive: true, force: true }));
  return { root, target: path.join(root, 'artifact.json') };
}
const error = code => Object.assign(new Error('injected ' + code), { code });
const clean = (root, target) => assert.deepEqual(fs.readdirSync(root), [path.basename(target)]);

test('identical generated bytes retain modification time without staging or replacing', t => {
  const { root, target } = fixture(t),
    data = Buffer.from('δ = 1\n');
  fs.writeFileSync(target, data);
  const modified = fs.statSync(target).mtimeMs;
  const write = createWriter({
    filesystem: {
      ...fs,
      openSync() {
        assert.fail('Unchanged bytes staged.');
      }
    }
  });
  assert.equal(write(target, 'δ = 1\n'), false);
  assert.equal(fs.statSync(target).mtimeMs, modified);
  assert.deepEqual(fs.readFileSync(target), data);
  clean(root, target);
});

test('new files stage exact UTF-8 bytes beside their destination before atomic replacement', t => {
  const { root } = fixture(t),
    target = path.join(root, 'nested', 'artifact.js'),
    data = Buffer.from('globalThis.value = "μ − δ";\n');
  let observed = 0;
  const write = createWriter({
    filesystem: {
      ...fs,
      renameSync(source, destination) {
        assert.equal(path.dirname(source), path.dirname(target));
        assert.deepEqual(fs.readFileSync(source), data);
        assert.equal(fs.existsSync(target), false);
        observed++;
        fs.renameSync(source, destination);
      }
    }
  });
  assert.equal(write(target, data), true);
  assert.deepEqual(fs.readFileSync(target), data);
  assert.equal(observed, 1);
  clean(path.dirname(target), target);
});

test('Windows UNKNOWN and sharing failures retry at most three times without truncating old bytes', t => {
  const { root, target } = fixture(t),
    delays = [];
  fs.writeFileSync(target, 'previous\n');
  let attempts = 0;
  const write = createWriter({
    platform: 'win32',
    sleep: ms => delays.push(ms),
    filesystem: {
      ...fs,
      renameSync(source, destination) {
        attempts++;
        assert.equal(fs.readFileSync(target, 'utf8'), 'previous\n');
        if (attempts === 1) throw Object.assign(error('UNKNOWN'), { errno: -4094 });
        if (attempts === 2) throw error('EPERM');
        fs.renameSync(source, destination);
      }
    }
  });
  assert.equal(write(target, 'completed\n'), true);
  assert.equal(attempts, 3);
  assert.deepEqual(delays, [100, 200]);
  assert.equal(fs.readFileSync(target, 'utf8'), 'completed\n');
  clean(root, target);
});

test('persistent Windows failures propagate the original error after three attempts with clean staging', t => {
  const { root, target } = fixture(t),
    delays = [],
    failure = error('EINVAL');
  fs.writeFileSync(target, 'previous\n');
  let attempts = 0;
  const write = createWriter({
    platform: 'win32',
    sleep: ms => delays.push(ms),
    filesystem: {
      ...fs,
      renameSync() {
        attempts++;
        throw failure;
      }
    }
  });
  assert.throws(
    () => write(target, 'never published\n'),
    value => value === failure
  );
  assert.equal(attempts, 3);
  assert.deepEqual(delays, [100, 200]);
  assert.equal(fs.readFileSync(target, 'utf8'), 'previous\n');
  clean(root, target);
});

test('failed partial staging closes the descriptor and never publishes a prefix', t => {
  const { root, target } = fixture(t),
    failure = error('UNKNOWN');
  fs.writeFileSync(target, 'previous\n');
  let attempts = 0;
  const write = createWriter({
    platform: 'win32',
    sleep() {},
    filesystem: {
      ...fs,
      writeFileSync(descriptor, data) {
        attempts++;
        fs.writeFileSync(descriptor, data.subarray(0, 2));
        throw failure;
      },
      renameSync() {
        assert.fail('Incomplete bytes published.');
      }
    }
  });
  assert.throws(
    () => write(target, 'never publish a prefix\n'),
    value => value === failure
  );
  assert.equal(attempts, 3);
  assert.equal(fs.readFileSync(target, 'utf8'), 'previous\n');
  clean(root, target);
});

test('unrelated errors and non-Windows EINVAL or permission failures propagate immediately', t => {
  const { root, target } = fixture(t);
  fs.writeFileSync(target, 'previous\n');
  for (const [platform, code] of [
    ['win32', 'EIO'],
    ['linux', 'EINVAL'],
    ['linux', 'EACCES']
  ]) {
    let attempts = 0;
    const failure = error(code),
      write = createWriter({
        platform,
        sleep() {
          assert.fail('Non-retryable error slept.');
        },
        filesystem: {
          ...fs,
          renameSync() {
            attempts++;
            throw failure;
          }
        }
      });
    assert.throws(
      () => write(target, 'never published\n'),
      value => value === failure
    );
    assert.equal(attempts, 1);
    assert.equal(fs.readFileSync(target, 'utf8'), 'previous\n');
    clean(root, target);
  }
});

test('exclusive temporary creation never deletes an unowned collision', t => {
  const { root, target } = fixture(t),
    failure = error('EEXIST');
  fs.writeFileSync(target, 'previous\n');
  const write = createWriter({
    platform: 'win32',
    filesystem: {
      ...fs,
      openSync() {
        throw failure;
      },
      unlinkSync() {
        assert.fail('Unowned staging path deleted.');
      }
    }
  });
  assert.throws(
    () => write(target, 'never published\n'),
    value => value === failure
  );
  clean(root, target);
});

test('generated write rejects unsupported values before touching the filesystem', () => {
  assert.throws(() => writeGenerated('unused', { value: 'not serialized' }), TypeError);
});
