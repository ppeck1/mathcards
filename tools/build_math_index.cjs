#!/usr/bin/env node
/* Build-only projection. Reuse the exact reference compiler used by fixtures. */
'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
require(path.join(root,'src/catalog.js'));
const Index=require(path.join(root,'src/math-index.js'));
const Stories=require(path.join(root,'src/story-library.js'));
const data=Index.compile({...globalThis.AtlasCatalog,stories:Stories.all()});
// Keep the projection inert in both an external script and the standalone
// inline bundle. Sources remain canonical cards, stories and reference terms.
const payload=JSON.stringify(data).replace(/&/g,'\\u0026').replace(/</g,'\\u003c').replace(/>/g,'\\u003e').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
const target=process.argv[2]||path.join(root,'src/math-index-data.js');
const source='/* Generated by tools/build_math_index.cjs. Do not edit. */\nglobalThis.AtlasMathIndexData = '+payload+';\n';
// Leave identical generated data untouched, including when a Windows viewer
// briefly holds the existing file open during a repeat build.
if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==source)fs.writeFileSync(target,source,'utf8');
