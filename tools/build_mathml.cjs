#!/usr/bin/env node
/* Build-only TeX compiler. The application receives native MathML, never a TeX parser. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {writeGenerated} = require('./generated_io.cjs');
const Temml = require('./vendor/temml/temml.cjs');
const ROOT = path.resolve(__dirname, '..');
const settings = Object.freeze({displayMode:true,strict:true,throwOnError:true,trust:false,xml:true,annotate:true});

function compile(cards) {
  if (!Array.isArray(cards)) throw new TypeError('Formula compilation requires canonical cards.');
  const bySlug = Object.create(null);
  for (const card of [...cards].sort((a,b)=>String(a?.slug)<String(b?.slug)?-1:String(a?.slug)>String(b?.slug)?1:0)) {
    const slug = card?.slug, tex = card?.definition?.formal_latex;
    if (typeof slug !== 'string' || !/^[a-z][a-z0-9-]*$/.test(slug)) throw new TypeError('A formula requires a canonical slug.');
    if (Object.hasOwn(bySlug,slug)) throw new TypeError('Duplicate formula slug: '+slug);
    if (typeof tex !== 'string' || !tex.trim()) throw new TypeError('Missing formal_latex for '+slug);
    try {
      const mathml = Temml.renderToString(tex, settings);
      if (!mathml.startsWith('<math ') || !mathml.includes('<semantics>') || !mathml.includes('<annotation encoding="application/x-tex">')) throw new Error('Compiler did not produce annotated native MathML.');
      bySlug[slug] = mathml;
    } catch (cause) {
      throw new Error('Cannot typeset '+slug+': '+cause.message, {cause});
    }
  }
  return {formatVersion:1,compiler:{name:'Temml',version:Temml.version},bySlug};
}
function script(data) {
  const payload = JSON.stringify(data).replace(/&/g,'\\u0026').replace(/</g,'\\u003c').replace(/>/g,'\\u003e').replace(/\u2028/g,'\\u2028').replace(/\u2029/g,'\\u2029');
  return '/* Generated by tools/build_mathml.cjs using Temml '+Temml.version+'. Do not edit. */\nglobalThis.AtlasFormulaData = '+payload+';\n';
}
function write(cards, target=path.join(ROOT,'src/formula-data.js')) {
  const data = compile(cards), output = script(data);
  writeGenerated(target,output);
  return data;
}
if (require.main === module) {
  const cards = fs.readdirSync(path.join(ROOT,'content/cards')).filter(name=>name.endsWith('.json')).map(name=>JSON.parse(fs.readFileSync(path.join(ROOT,'content/cards',name),'utf8')));
  const data = write(cards,process.argv[2] ? path.resolve(process.argv[2]) : undefined);
  console.log(JSON.stringify({compiler:data.compiler,formulas:Object.keys(data.bySlug).length}));
}
module.exports = Object.freeze({compile,script,write});
